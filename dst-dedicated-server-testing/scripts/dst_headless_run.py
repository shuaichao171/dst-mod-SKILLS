# lan_only_cluster 的 server_port 必须在此范围内，否则专服会改用 10999（实测 build 761239）
LAN_PORT_RANGE = (10998, 11018)


def free_port(used, lo=20000, hi=40000):
    candidates = list(range(lo, hi + 1))
    random.shuffle(candidates)
    for port in candidates[:400]:
        if port in used:
            continue
        try:
            for kind in (socket.SOCK_DGRAM, socket.SOCK_STREAM):
                with socket.socket(socket.AF_INET, kind) as s:
                    s.bind(("0.0.0.0", port))
        except OSError:
            continue
        used.add(port)
        return port
    raise RuntimeError(f"{lo}-{hi} 范围内找不到空闲端口")


def lua_value(v):
    if v is None:
        return "nil"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, list):
        return "{" + ", ".join(lua_value(x) for x in v) + "}"
    if isinstance(v, dict):
        return "{" + ", ".join(f"[{json.dumps(str(k), ensure_ascii=False)}]={lua_value(x)}" for k, x in v.items()) + "}"
    raise ValueError(f"无法转换为 Lua：{v!r}")


def write_cluster(storage, ports, mod_entries):
    cluster = storage / CONF_DIR / CLUSTER
    master = cluster / "Master"
    master.mkdir(parents=True)
    (cluster / "cluster.ini").write_text(
        "[GAMEPLAY]\ngame_mode = endless\nmax_players = 1\npvp = false\npause_when_empty = false\nvote_enabled = false\n\n"
        "[NETWORK]\ncluster_name = altwf headless test\ncluster_description = isolated offline test\n"
        "cluster_intention = cooperative\noffline_cluster = true\nlan_only_cluster = true\ntick_rate = 30\n\n"
        "[MISC]\nconsole_enabled = true\nmax_snapshots = 1\n\n[SHARD]\nshard_enabled = false\n", encoding="utf-8")
    (master / "server.ini").write_text(
        f"[NETWORK]\nserver_port = {ports['server']}\n\n[SHARD]\nis_master = true\nid = 1\n\n"
        f"[STEAM]\nmaster_server_port = {ports['master']}\nauthentication_port = {ports['auth']}\n\n"
        "[ACCOUNT]\nencode_user_path = true\n", encoding="utf-8")
    (master / "modoverrides.lua").write_text("return " + lua_value(mod_entries) + "\n", encoding="utf-8")
    return master / "server_log.txt"


# ---------------------------------------------------------------- 日志解析与判定

def parse_event(line, run_id):
    tag = f"[ALTTEST {run_id}] "
    i = line.find(tag)
    if i < 0:
        return None
    kind, _, payload = line[i + len(tag):].strip().partition(" ")
    try:
        data = json.loads(payload) if payload else {}
    except ValueError:
        data = {"raw": payload}
    return {"kind": kind, **(data if isinstance(data, dict) else {"value": data})}


LOADED_RE = re.compile(r"Loading mod: (\S+) \(")


class LogState:
    def __init__(self, run_id):
        self.run_id = run_id
        self.events, self.errors, self.loaded = [], [], []
        self.ready = self.done = False
        self._capture = 0

    def feed(self, line):
        line = line.rstrip("\r\n")
        ev = parse_event(line, self.run_id)
        if ev:
            self.events.append(ev)
            self.ready |= ev["kind"] == "READY"
            self.done |= ev["kind"] == "DONE"
            if ev["kind"] == "SCRIPT_ERROR":
                self.errors.append({"after_ready": True, "lines": [line]})
            return
        m = LOADED_RE.search(line)
        if m:
            self.loaded.append(m.group(1))
        if any(p in line for p in FAIL_PATTERNS):
            if self._capture and self.errors:
                self.errors[-1]["lines"].append(line)
            else:
                self.errors.append({"after_ready": self.ready, "lines": [line]})
            self._capture = 15
        elif self._capture and self.errors:
            self.errors[-1]["lines"].append(line)
            self._capture -= 1


def tail(path, pos, state, final=False):
    """从字节偏移 pos 继续读日志，只喂完整行（final 时连最后半行一起），返回新偏移。"""
    if not path.exists():
        return pos
    with open(path, "rb") as f:
        f.seek(pos)
        chunk = f.read()
    cut = len(chunk) if final else chunk.rfind(b"\n") + 1
    for line in chunk[:cut].decode("utf-8", "replace").splitlines():
        state.feed(line)
    return pos + cut


def decide(state, expected_keys, timed_out, exit_code):
    checks = [e for e in state.events if e["kind"] == "CHECK"]
    failed_checks = [c for c in checks if not c.get("ok")]
    missing = [k for k in expected_keys if k not in state.loaded]
    invalid = next((e for e in state.events if e["kind"] == "INVALID"), None)
    if missing and not state.ready:
        return "interrupted", f"世界未就绪，且以下模组没有加载：{', '.join(missing)}"
    if missing:
        return "invalid", f"以下模组没有加载，测试不代表被测代码：{', '.join(missing)}"
    if not state.done:
        if timed_out:
            return "interrupted", "超时：没有收到本次 run_id 的 DONE（行为脚本需在全部断言后调用 TEST.Done）"
        return "interrupted", f"专服在完成前退出（退出码 {exit_code}）"
    if invalid:
        return "invalid", f"行为脚本标记无效：{invalid.get('reason')}"
    if failed_checks or any(e["kind"] == "SCRIPT_ERROR" for e in state.events):
        return "failed", f"{len(failed_checks)} 项断言失败" + ("，行为脚本报错" if any(
            e["kind"] == "SCRIPT_ERROR" for e in state.events) else "")
    if any(err["after_ready"] for err in state.errors):
        return "failed", "断言都通过，但运行期日志出现错误（见 first_error）"
    if not checks:
        return "invalid", "行为脚本没有任何断言"
    return "passed", f"{len(checks)} 项断言全部通过"


# ---------------------------------------------------------------- 主流程

def server_command(game_home, storage, ugc, x86=False, sandbox_escape=False):
    exe = (game_home / "bin" / "dontstarve_dedicated_server_nullrenderer.exe") if x86 else \
        (game_home / "bin64" / "dontstarve_dedicated_server_nullrenderer_x64.exe")
    if os.name != "nt":
        exe = exe.with_name(exe.stem.replace("_x64", "")) if x86 else exe.with_suffix("")
    cmd = [str(exe), "-console", "-offline", "-persistent_storage_root", str(storage), "-conf_dir", CONF_DIR,
           "-cluster", CLUSTER, "-shard", "Master", "-bind_ip", "127.0.0.1", "-skip_update_server_mods",
           "-ugc_directory", str(ugc)]
    if sandbox_escape:
        cmd += ["-allow_persistentstorage_read_sandbox_escape", "-allow_persistentstorage_write_sandbox_escape"]
    return exe, cmd


def now_iso():
    return datetime.datetime.now().astimezone().isoformat(timespec="seconds")


def run(args, server_cmd_override=None):
    game_home = Path(args.game_home or os.environ.get("DST_GAME_HOME", "")).resolve()
    if not args.game_home and not os.environ.get("DST_GAME_HOME"):
        raise ValueError("需要 --game-home 或环境变量 DST_GAME_HOME")
    mods_root = game_home / "mods"
    behavior = Path(args.behavior).resolve()
    if not behavior.is_file():
        raise ValueError(f"行为脚本不存在：{behavior}")
    for m in args.mod:
        if not (Path(m) / "modinfo.lua").is_file():
            raise ValueError(f"不是模组目录（缺少 modinfo.lua）：{m}")
    mod_config = json.loads(Path(args.mod_config).read_text(encoding="utf-8")) if args.mod_config else {}

    run_id = datetime.datetime.now().strftime("%Y%m%dT%H%M%S") + "_" + uuid.uuid4().hex[:6]
    run_dir = Path(args.out).resolve() / run_id
    storage, ugc, logs, results = (run_dir / d for d in ("storage", "ugc", "logs", "results"))
    for d in (storage, ugc, logs, results):
        d.mkdir(parents=True)
    exe, cmd = server_command(game_home, storage, ugc, args.x86, args.allow_sandbox_escape)
    if server_cmd_override:
        cmd = server_cmd_override + cmd[1:]
    result = {"run_id": run_id, "status": "not_run", "started_at": now_iso(), "game_home": str(game_home),
              "build": None, "server_exe": str(exe), "behavior": str(behavior), "mods": [], "runner": None,
              "ports": None, "process": None, "checks": [], "metrics": [], "first_error": None,
              "staged_removed": False, "limits": "只验证服务端引擎逻辑；不覆盖贴图、UI、音画、客户端预测与网络同步"}
    version = game_home / "version.txt"
    if version.is_file():
        result["build"] = version.read_text(encoding="utf-8", errors="replace").strip()

    if args.dry_run:
        result["plan"] = {"stage": [str(Path(m).resolve()) for m in args.mod], "command": cmd,
                          "mods_root": str(mods_root)}
        (results / "result.json").write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding="utf-8")
        return result, run_dir
    if not server_cmd_override and not exe.is_file():
        raise ValueError(f"找不到无渲染专服程序：{exe}")

    staged, state, proc, handles = [], LogState(run_id), None, []
    try:
        for i, m in enumerate(args.mod):
            info = stage_mod(m, mods_root / f"{PREFIX}{run_id}_{i}")
            staged.append(Path(info["staged"]))
            result["mods"].append(info)
        runner = write_runner(mods_root, run_id, behavior, args.start_delay)
        staged.append(Path(runner["staged"]))
        result["runner"] = runner

        entries = {}
        for info in result["mods"]:
            opts = mod_config.get(Path(info["source"]).name)
            entries[info["key"]] = {"enabled": True, **({"configuration_options": opts} if opts else {})}
        entries[runner["key"]] = {"enabled": True}
        used = set()
        ports = {"server": free_port(used, *LAN_PORT_RANGE), "master": free_port(used), "auth": free_port(used)}
        result["ports"] = ports
        log_path = write_cluster(storage, ports, entries)

        stdout = open(logs / "server.stdout.log", "wb")
        handles.append(stdout)
        flags = subprocess.CREATE_NO_WINDOW if os.name == "nt" else 0
        started = time.time()
        proc = subprocess.Popen(cmd, cwd=str(Path(cmd[0]).parent) if not server_cmd_override else None,
                                stdin=subprocess.PIPE, stdout=stdout, stderr=subprocess.STDOUT, creationflags=flags)
        result["process"] = {"pid": proc.pid, "command": cmd, "started_at": now_iso()}
        print(f"[{run_id}] 专服已启动 pid={proc.pid}，等待世界就绪 ...", file=sys.stderr)

        events_file = open(results / "events.jsonl", "w", encoding="utf-8")
        handles.append(events_file)
        pos, timed_out, shutdown_at = 0, False, None
        n_events, ready_at = 0, None
        while True:
            pos = tail(log_path, pos, state)
            for ev in state.events[n_events:]:
                events_file.write(json.dumps(ev, ensure_ascii=False) + "\n")
                if ev["kind"] in ("CHECK", "SCRIPT_ERROR", "INVALID", "DONE"):
                    print(f"[{run_id}] {ev['kind']} {ev.get('name', '')} "
                          f"{'' if ev.get('ok', True) else 'FAIL ' + str(ev.get('detail'))}".rstrip(), file=sys.stderr)
            n_events = len(state.events)
            if state.ready and ready_at is None:
                ready_at = time.time()
                print(f"[{run_id}] 世界就绪（{ready_at - started:.0f}s），开始执行行为脚本", file=sys.stderr)
            elapsed = time.time() - started
            if shutdown_at is None and (state.done or elapsed > args.timeout or
                                        (not state.ready and elapsed > args.startup_timeout)):
                timed_out = not state.done
                shutdown_at = time.time()
                try:
                    proc.stdin.write(b"c_shutdown(false)\n")
                    proc.stdin.flush()
                except OSError:
                    pass
            if proc.poll() is not None:
                break
            if shutdown_at is not None and time.time() - shutdown_at > args.shutdown_timeout:
                proc.terminate()
                try:
                    proc.wait(10)
                except subprocess.TimeoutExpired:
                    proc.kill()
                    proc.wait(10)
                result["process"]["forced_kill"] = True
                break
            time.sleep(0.5)
        tail(log_path, pos, state, final=True)  # 退出前最后几行
        if log_path.exists():
            shutil.copyfile(log_path, logs / "server_log.txt")
        result["process"].update(exit_code=proc.returncode, ended_at=now_iso(),
                                 ready_after_s=round(ready_at - started, 1) if ready_at else None)
        expected = [info["key"] for info in result["mods"]] + [runner["key"]]
        result["status"], result["reason"] = decide(state, expected, timed_out, proc.returncode)
        result["loaded_mods"] = sorted(set(state.loaded))
        result["checks"] = [e for e in state.events if e["kind"] == "CHECK"]
        result["metrics"] = [e for e in state.events if e["kind"] == "METRIC"]
        result["first_error"] = state.errors[0] if state.errors else None
        result["errors_total"] = len(state.errors)
    finally:
        if proc is not None and proc.poll() is None:  # 异常路径：只终止本次启动的进程
            proc.kill()
            proc.wait(10)
        if proc is not None and proc.stdin:
            proc.stdin.close()
        for h in handles:
            h.close()
        if not args.keep_staged:
            for path in staged:
                if path.exists():
                    remove_owned(path, mods_root, run_id)
            result["staged_removed"] = True
        result["ended_at"] = now_iso()
        (results / "result.json").write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding="utf-8")
    return result, run_dir


def stale_dirs(game_home):
    mods = Path(game_home) / "mods"
    return sorted(p for p in mods.iterdir() if p.is_dir() and p.name.startswith(PREFIX)) if mods.is_dir() else []


def main(argv=None):
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="replace")
    p = argparse.ArgumentParser(description="DST 隔离无头测试（原生专服 + 行为脚本）")
    p.add_argument("--mod", action="append", default=[], help="被测模组目录；依赖先写，可重复")
    p.add_argument("--behavior", help="行为脚本 .lua（使用 TEST API，最后调用 TEST.Done）")
    p.add_argument("--out", help="结果根目录，建议 <目标项目>/_ai_work/headless")
    p.add_argument("--game-home", help="DST 安装根目录（默认环境变量 DST_GAME_HOME）")
    p.add_argument("--mod-config", help="JSON：{\"模组目录名\": {配置项: 值}}，写入 modoverrides 的 configuration_options")
    p.add_argument("--start-delay", type=float, default=2, help="世界就绪后多少秒执行行为脚本（默认 2）")
    p.add_argument("--timeout", type=int, default=900, help="总时长上限秒数（默认 900，含建世界）")
    p.add_argument("--startup-timeout", type=int, default=600, help="等待世界就绪的上限秒数（默认 600）")
    p.add_argument("--shutdown-timeout", type=int, default=60, help="发出关服命令后等待退出的秒数（默认 60）")
    p.add_argument("--x86", action="store_true", help="使用 32 位 bin/ 下的专服")
    p.add_argument("--allow-sandbox-escape", action="store_true",
                   help="追加持久化目录沙箱放行参数（仅被测模组需要读写集群目录外文件时）")
    p.add_argument("--keep-staged", action="store_true", help="结束后保留复制到 mods/ 的快照（便于排查）")
    p.add_argument("--dry-run", action="store_true", help="只生成计划，不复制、不启动")
    p.add_argument("--list-stale", action="store_true", help="列出 mods/ 里本工具遗留的测试快照")
    p.add_argument("--remove-stale", action="store_true", help="删除 mods/ 里本工具遗留的测试快照")
    args = p.parse_args(argv)

    if args.list_stale or args.remove_stale:
        home = args.game_home or os.environ.get("DST_GAME_HOME")
        if not home:
            print("[错误] 需要 --game-home 或环境变量 DST_GAME_HOME", file=sys.stderr)
            return 2
        dirs = stale_dirs(home)
        for d in dirs:
            if args.remove_stale:
                remove_owned(d, Path(home) / "mods")
            print(("已删除 " if args.remove_stale else "") + d.name)
        print(f"共 {len(dirs)} 个", file=sys.stderr)
        return 0
    if not (args.mod and args.behavior and args.out):
        p.error("需要 --mod、--behavior 和 --out")
    try:
        result, run_dir = run(args)
    except (ValueError, RuntimeError, OSError) as e:
        print(f"[错误] {e}", file=sys.stderr)
        return 2
    summary = {k: result.get(k) for k in ("run_id", "status", "reason", "build", "errors_total", "staged_removed")}
    summary["passed"] = sum(1 for c in result["checks"] if c.get("ok"))
    summary["failed"] = sum(1 for c in result["checks"] if not c.get("ok"))
    summary["result"] = str(run_dir / "results" / "result.json")
    print(json.dumps(summary, ensure_ascii=False, indent=2))
    return EXIT_CODES.get(result["status"], 4)


if __name__ == "__main__":
    sys.exit(main())
