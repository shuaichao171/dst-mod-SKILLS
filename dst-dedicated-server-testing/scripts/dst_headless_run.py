RUNNER_MODMAIN = r"""-- Generated by alt_workflow dst_headless_run.py for run %RUN_ID%. Temporary; never publish.
GLOBAL.setmetatable(env, { __index = function(t, k) return GLOBAL.rawget(GLOBAL, k) end })
local json = GLOBAL.require("json")
local RUN_ID = "%RUN_ID%"
local START_DELAY = %START_DELAY%
local TAG = "[ALTTEST " .. RUN_ID .. "] "

local function emit(kind, data)
    local ok, s = pcall(json.encode, data or {})
    print(TAG .. kind .. " " .. (ok and s or '{"encode_error":true}'))
end

local T = { run_id = RUN_ID, passed = 0, failed = 0, done = false, spawned = {} }
TEST = T

function T.Log(msg) emit("LOG", { msg = tostring(msg) }) end

function T.Check(name, ok, detail)
    if T.done then return ok end
    ok = ok and true or false
    if ok then T.passed = T.passed + 1 else T.failed = T.failed + 1 end
    emit("CHECK", { name = tostring(name), ok = ok, detail = detail ~= nil and tostring(detail) or nil })
    return ok
end

function T.Equal(name, actual, expected)
    return T.Check(name, actual == expected, "actual=" .. tostring(actual) .. " expected=" .. tostring(expected))
end

function T.Near(name, actual, expected, eps)
    eps = eps or 1e-4
    local ok = type(actual) == "number" and type(expected) == "number" and math.abs(actual - expected) <= eps
    return T.Check(name, ok, "actual=" .. tostring(actual) .. " expected=" .. tostring(expected) .. " eps=" .. tostring(eps))
end

function T.Metric(name, value) emit("METRIC", { name = tostring(name), value = value }) end

function T.Spawn(prefab, x, z)
    local inst = SpawnPrefab(prefab)
    if inst == nil then return nil end
    if x ~= nil and inst.Transform ~= nil then inst.Transform:SetPosition(x, 0, z or 0) end
    table.insert(T.spawned, inst)
    return inst
end

function T.Cleanup()
    for _, inst in ipairs(T.spawned) do
        if inst:IsValid() then inst:Remove() end
    end
    T.spawned = {}
end

function T.Done(note)
    if T.done then return end
    T.done = true
    pcall(T.Cleanup)
    emit("DONE", { passed = T.passed, failed = T.failed, note = note ~= nil and tostring(note) or nil })
end

function T.Error(err)
    if T.done then return end
    emit("SCRIPT_ERROR", { error = tostring(err) })
    T.failed = T.failed + 1
    T.Done("script error")
end

function T.Invalid(reason)
    if T.done then return end
    emit("INVALID", { reason = tostring(reason) })
    T.Done("invalid")
end

function T.After(seconds, fn)
    return TheWorld:DoTaskInTime(seconds, function()
        local ok, err = pcall(fn)
        if not ok then T.Error(err) end
    end)
end

AddSimPostInit(function()
    if not TheWorld.ismastersim then return end
    emit("READY", { dedicated = TheNet:IsDedicated() == true })
    TheWorld:DoTaskInTime(START_DELAY, function()
        emit("START", {})
        local ok, err = pcall(modimport, "scripts/%BEHAVIOR%")
        if not ok then T.Error(err) end
    end)
end)
"""


# ---------------------------------------------------------------- 快照

def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def is_link(path):
    """符号链接或 Windows junction（重解析点）。"""
    if path.is_symlink():
        return True
    try:
        attrs = os.lstat(path).st_file_attributes  # 只有 Windows 有
    except (AttributeError, OSError):
        return False
    return bool(attrs & stat.FILE_ATTRIBUTE_REPARSE_POINT)


def manifest(root):
    root = Path(root)
    return {p.relative_to(root).as_posix(): sha256(p) for p in sorted(root.rglob("*")) if p.is_file()}


def stage_mod(source, target):
    source = Path(source).resolve()
    if not (source / "modinfo.lua").is_file():
        raise ValueError(f"不是模组目录（缺少 modinfo.lua）：{source}")
    for p in [source, *source.rglob("*")]:
        if is_link(p):
            raise ValueError(f"模组里有符号链接或 junction，拒绝复制：{p}")
    if target.exists():
        raise ValueError(f"快照目录已存在：{target}")
    before = manifest(source)
    shutil.copytree(source, target, ignore=shutil.ignore_patterns("_ai_work", ".git"))
    expected = {k: v for k, v in before.items() if not set(k.split("/")[:-1]) & {"_ai_work", ".git"}}
    after = manifest(target)
    if after != expected or manifest(source) != before:
        raise ValueError(f"复制过程中源目录发生变化或复制不完整：{source}（快照保留在 {target}）")
    return {"source": str(source), "staged": str(target), "key": target.name,
            "files": len(after), "sha256": hashlib.sha256(json.dumps(after, sort_keys=True).encode()).hexdigest()}


def write_runner(mods_root, run_id, behavior, start_delay):
    target = mods_root / f"{PREFIX}{run_id}_runner"
    (target / "scripts").mkdir(parents=True)
    (target / "modinfo.lua").write_text(RUNNER_MODINFO, encoding="utf-8")
    modmain = (RUNNER_MODMAIN.replace("%RUN_ID%", run_id).replace("%START_DELAY%", repr(float(start_delay)))
               .replace("%BEHAVIOR%", BEHAVIOR_NAME))
    (target / "modmain.lua").write_text(modmain, encoding="utf-8")
    shutil.copyfile(behavior, target / "scripts" / BEHAVIOR_NAME)
    return {"key": target.name, "staged": str(target), "behavior_sha256": sha256(behavior)}


def remove_owned(path, mods_root, run_id=None):
    """只删除 mods/ 下本工具前缀的目录；run_id 给定时还要求属于该次运行。"""
    path, mods_root = Path(path).resolve(), Path(mods_root).resolve()
    prefix = f"{PREFIX}{run_id}_" if run_id else PREFIX
    if path.parent != mods_root or not path.name.startswith(prefix):
        raise ValueError(f"拒绝删除不属于本次测试的目录：{path}")
    shutil.rmtree(path)


