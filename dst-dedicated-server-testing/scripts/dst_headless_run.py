#!/usr/bin/env python3
"""DST 隔离无头测试：快照被测模组 → 独立集群启动原生专服 → 运行行为脚本 → 判定 → 关服清理。

    python dst_headless_run.py --mod <模组目录> --behavior <行为脚本.lua> --out <目标项目>/_ai_work/headless
    python dst_headless_run.py --mod <依赖> --mod <被测模组> --behavior case.lua --out ... --timeout 900
    python dst_headless_run.py --list-stale            # 列出以前运行遗留在游戏 mods/ 的测试快照
    python dst_headless_run.py --remove-stale          # 删除这些遗留快照（只删本工具前缀的目录）

做什么：
1. 每次运行生成唯一 run_id，把 --mod 指定的模组复制到 <DST_GAME_HOME>/mods/_altwf_<run_id>_<n>，
   复制前后比对 SHA-256 清单；拒绝符号链接/junction；同时生成一个测试驱动模组（不进入正式模组）。
2. 在 <out>/<run_id>/storage 建独立集群（离线、单分片、空服不暂停、随机空闲端口），
   -ugc_directory 也指向本次目录，不碰用户存档。
3. 启动 bin64 无渲染专服（--x86 用 bin），世界就绪后等 --start-delay 秒，在驱动模组环境里执行行为脚本。
4. 行为脚本用全局 TEST 断言，最后必须调用 TEST.Done()；读到本次 run_id 的 DONE 才算执行完成。
5. 发 c_shutdown(false) 正常关服，超时才终止本次启动的进程；删除本次复制到 mods/ 的快照（--keep-staged 保留）。

行为脚本 API（在驱动模组环境执行，可直接访问 GLOBAL 的 TheWorld、SpawnPrefab 等）：
    TEST.Check(name, ok, detail)    TEST.Equal(name, actual, expected)    TEST.Near(name, a, b, eps)
    TEST.Metric(name, value)        TEST.Log(msg)                         TEST.Spawn(prefab, x, z)
    TEST.After(seconds, fn)         -- 延时执行，fn 内报错会记为 SCRIPT_ERROR 并结束
    TEST.Invalid(reason)            -- 前置条件不成立：结果记为无效
    TEST.Done(note)                 -- 全部断言之后调用；会先移除 TEST.Spawn 生成的实体

结果：<out>/<run_id>/results/result.json（状态、断言、指标、首个错误、快照指纹、build、端口、进程信息），
events.jsonl（驱动输出的事件），logs/（专服日志与标准输出）。
状态与退出码：passed 0 / failed 1 / 环境或参数错误 2 / invalid 3 / interrupted 4 / 仅 --dry-run 0。
只验证服务端引擎逻辑；贴图、UI、音画、真实客户端预测与网络同步不在范围内。只用 Python 标准库。
"""
